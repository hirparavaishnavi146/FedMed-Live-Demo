"""Shared Pydantic base classes and response envelopes.

Field naming: the TypeScript frontend uses camelCase, so every response model
serialises to camelCase via an alias generator. Python code still uses
snake_case internally.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Generic, TypeVar

from pydantic import BaseModel, ConfigDict
from pydantic.alias_generators import to_camel

T = TypeVar("T")

# A single sentence repeated in every meta block, so a client (or a person
# reading a response by hand) can never mistake synthetic values for results.
SIMULATED_NOTICE = (
    "Synthetic values generated by the FedMed backend for interface development. "
    "No model is trained, no federated learning runs, no real hospital is "
    "connected and no patient data is present."
)


class CamelModel(BaseModel):
    """Base model that serialises snake_case fields as camelCase."""

    model_config = ConfigDict(
        alias_generator=to_camel,
        populate_by_name=True,
        from_attributes=True,
    )


class ResponseMeta(CamelModel):
    """Metadata attached to every /api/v1 response."""

    generated_at: datetime
    simulated: bool = True
    source: str = "synthetic"
    notice: str = SIMULATED_NOTICE


class Envelope(CamelModel, Generic[T]):
    """Standard successful response: the payload plus its metadata."""

    data: T
    meta: ResponseMeta


class ErrorBody(CamelModel):
    """The ``error`` object inside a failure response."""

    code: str
    message: str
    detail: dict[str, object] = {}


class ErrorResponse(CamelModel):
    """Standard failure response."""

    error: ErrorBody


def utc_now() -> datetime:
    """Timezone-aware UTC timestamp, used for every generated_at value."""
    return datetime.now(timezone.utc)


def make_meta(*, simulated: bool = True, source: str = "synthetic") -> ResponseMeta:
    return ResponseMeta(generated_at=utc_now(), simulated=simulated, source=source)
